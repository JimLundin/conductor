// Writes src/schemas/index.ts, the Effect Schemas of every definition in
// the JSON Schema the `link` crate publishes, crates/link/link.schema.json.
// The `schemas` suite runs both and fails on a difference from what is
// committed.
import { readFile, writeFile } from "node:fs/promises";
import { Array as Arr, Codegen, JsonSchema, SchemaRepresentation } from "effect";

const header = "// Generated by scripts/schemas.ts from link's link.schema.json. Do not edit.\n";

const print = (source: JsonSchema.JsonSchema): string => {
  const { definitions } = JsonSchema.fromSchemaDraft2020_12(source);
  const names = Object.keys(definitions);
  if (!Arr.isArrayNonEmpty(names)) {
    return header;
  }
  const schemas = SchemaRepresentation.fromJsonSchemaMultiDocument(
    {
      dialect: "draft-2020-12",
      schemas: Arr.map(names, (name) => ({ $ref: `#/$defs/${name}` })),
      definitions,
    },
    { closeObjects: true },
  );
  const document = SchemaRepresentation.toRepresentations(Arr.map(schemas, (schema) => schema.ast));
  const module = new Codegen.Module();
  module.addSchemas(Object.fromEntries(Arr.zip(names, document.representations)), {
    references: document.references,
  });
  return header + module.print();
};

const published = new URL("../../crates/link/link.schema.json", import.meta.url);
await writeFile(
  new URL("../src/schemas/index.ts", import.meta.url),
  print(JSON.parse(await readFile(published, "utf8"))),
);
