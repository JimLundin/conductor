use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const FLOW: &str = include_str!("../../home/src/flow/test-flow.toml");
const DOC: &str = "# Home\n\n<!-- repos:start -->\n<!-- repos:end -->\nafter\n";

struct Scratch(PathBuf);

impl Drop for Scratch {
    fn drop(&mut self) {
        let _removed = fs::remove_dir_all(&self.0);
    }
}

fn git(at: &Path, args: &[&str]) -> std::io::Result<String> {
    let ran = Command::new("git")
        .arg("-C")
        .arg(at)
        .args(["-c", "user.name=test", "-c", "user.email=test@example.com"])
        .args(args)
        .output()?;
    assert!(
        ran.status.success(),
        "{}",
        String::from_utf8_lossy(&ran.stderr)
    );
    Ok(String::from_utf8_lossy(&ran.stdout).trim().to_owned())
}

fn repository(at: &Path, file: &str) -> std::io::Result<String> {
    fs::create_dir_all(at)?;
    fs::write(at.join(file), "")?;
    git(at, &["init", "-q", "-b", "main"])?;
    git(at, &["add", "."])?;
    git(at, &["commit", "-q", "-m", "first"])?;
    git(at, &["rev-parse", "HEAD"])
}

fn home(root: &Path, args: &[&str]) -> std::io::Result<(String, Output)> {
    let ran = Command::new(env!("CARGO_BIN_EXE_home"))
        .args(args)
        .current_dir(root)
        .env("HOME", root.join("user"))
        .output()?;
    let said = String::from_utf8_lossy(&ran.stdout).into_owned();
    assert!(ran.status.success(), "{said}");
    Ok((said, ran))
}

fn project(root: &Path, id: &str, text: &str) -> std::io::Result<()> {
    let folder = root.join("projects").join(id);
    fs::create_dir_all(&folder)?;
    fs::write(folder.join("project.toml"), text)
}

#[test]
fn repos_reports_scans_syncs_and_copies_skills() -> std::io::Result<()> {
    let scratch = Scratch(
        std::env::temp_dir().join(format!("home-repos-{}", std::process::id())),
    );
    let root = &scratch.0;
    fs::create_dir_all(root.join("docs/agents"))?;
    fs::write(root.join("docs/agents/flow.toml"), FLOW)?;
    fs::write(root.join("AGENTS.md"), DOC)?;
    let one = repository(&root.join("one"), "README.md")?;
    let two = repository(&root.join("apps/Two"), "Cargo.toml")?;
    let origin = root.join("one").display().to_string();
    project(
        root,
        "000001",
        &format!("name = \"one\"\ntitle = \"One\"\nroot = \"{one}\"\n"),
    )?;
    project(
        root,
        "000002",
        &format!(
            "name = \"copy\"\ntitle = \"Copy\"\nremote = {origin:?}\nroot = \"{one}\"\n"
        ),
    )?;

    let (said, _) = home(root, &["repos"])?;
    assert_eq!(
        said,
        format!(
            "{:<22} not checked out here\n{:<22} one: main\n",
            "copy", "one"
        )
    );

    let (said, _) = home(root, &["repos", "scan"])?;
    let added: Vec<String> = fs::read_dir(root.join("projects"))?
        .filter_map(Result::ok)
        .map(|entry| entry.file_name().to_string_lossy().into_owned())
        .filter(|name| !name.starts_with("00000"))
        .collect();
    let [id] = added.as_slice() else {
        return Err(std::io::Error::other(said));
    };
    assert_eq!(
        fs::read_to_string(
            root.join("projects").join(id).join("project.toml")
        )?,
        format!(
            "name = \"two\"\ntitle = \"Two\"\nroot = \"{two}\"\nprofiles = [\"rust\"]\n"
        )
    );
    assert_eq!(
        said,
        format!("added two as projects/{id} from apps/Two\ncopy\none\ntwo\n")
    );
    assert_eq!(
        fs::read_to_string(root.join("AGENTS.md"))?,
        format!(
            "# Home\n\n<!-- repos:start (generated by home repos scan from projects/) -->\n\
             | Project | Remote |\n|---|---|\n\
             | `copy` | {origin} |\n| `one` | local only |\n| `two` | local only |\n\
             <!-- repos:end -->\nafter\n"
        )
    );

    home(root, &["repos", "sync"])?;
    assert_eq!(
        git(&root.join("copy"), &["rev-list", "--max-parents=0", "HEAD"])?,
        one
    );
    fs::write(root.join("one/new.txt"), "")?;
    let (said, _) = home(root, &["repos"])?;
    assert!(said.contains("copy: main...origin/main\n"), "{said}");
    assert!(said.contains("one: main  [1 changed]\n"), "{said}");
    assert!(said.contains("apps/Two: main\n"), "{said}");

    let skill = root.join("skills/tdd");
    fs::create_dir_all(skill.join("more"))?;
    fs::write(skill.join("SKILL.md"), "tdd")?;
    fs::write(skill.join("more/notes.md"), "notes")?;
    let (said, _) = home(root, &["skills"])?;
    let claude = root.join("user/.claude/skills");
    assert_eq!(
        fs::read_to_string(claude.join("tdd/more/notes.md"))?,
        "notes"
    );
    assert_eq!(fs::read_to_string(claude.join(".home-skills"))?, "tdd\n");
    assert!(root.join("user/.agents/skills/tdd/SKILL.md").is_file());
    assert!(
        said.ends_with("/.agents/skills: 1 skills from the home\n"),
        "{said}"
    );
    Ok(())
}

fn verify(root: &Path) -> std::io::Result<(String, Option<i32>)> {
    let ran = Command::new(env!("CARGO_BIN_EXE_home"))
        .args(["repos", "--verify"])
        .current_dir(root)
        .env("HOME", root.join("user"))
        .output()?;
    Ok((
        String::from_utf8_lossy(&ran.stdout).into_owned(),
        ran.status.code(),
    ))
}

const CHECK: &str = "[ -e \"$3.passed\" ] && exit 0\n\
    echo 'lint                 FAIL  not yet'\n\
    echo 'missing . lint 5145a1b2c3d4e5f60718293a4b5c6d7e8f901234'\n\
    exit 1\n";

#[test]
fn verify_exits_nonzero_on_a_missing_pass_and_zero_on_every_pass()
-> std::io::Result<()> {
    let scratch = Scratch(
        std::env::temp_dir()
            .join(format!("home-repos-verify-{}", std::process::id())),
    );
    let origins = scratch.0.join("origins");
    let root = &scratch.0.join("home");
    fs::create_dir_all(root.join("docs/agents"))?;
    fs::write(root.join("docs/agents/flow.toml"), FLOW)?;
    let app = repository(&origins.join("app"), "README.md")?;
    fs::create_dir_all(origins.join("standards/fake"))?;
    fs::write(origins.join("standards/fake/check.sh"), CHECK)?;
    let standards = repository(&origins.join("standards"), "README.md")?;
    let app_origin = origins.join("app").display().to_string();
    let standards_origin = origins.join("standards").display().to_string();
    git(root, &["clone", "-q", &app_origin, "app"])?;
    git(root, &["clone", "-q", &standards_origin, "standards"])?;
    project(
        root,
        "000001",
        &format!(
            "name = \"app\"\ntitle = \"App\"\nremote = {app_origin:?}\nroot = \"{app}\"\nprofiles = [\"fake\"]\n"
        ),
    )?;
    project(
        root,
        "000002",
        &format!(
            "name = \"standards\"\ntitle = \"Standards\"\nremote = {standards_origin:?}\nroot = \"{standards}\"\nprovides = [\"fake\"]\n"
        ),
    )?;

    let (said, code) = verify(root)?;
    assert!(
        said.contains("app: no recorded `commit` pass for fake"),
        "{said}"
    );
    assert_eq!(code, Some(1), "{said}");

    fs::write(root.join("app.passed"), "")?;
    let (said, code) = verify(root)?;
    assert_eq!(
        said,
        format!(
            "{:<22} app: main...origin/main\n{:<22} standards: main...origin/main\n",
            "app", "standards"
        )
    );
    assert_eq!(code, Some(0), "{said}");
    Ok(())
}
